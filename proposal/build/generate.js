const nbNum = (s) => s.replace(/(?<=\d) (?=\d{3})/g, ' ');

function cell(content, { width, fill, bold, align, vAlign } = {}) {
  const paras = (Array.isArray(content) ? content : [content]).map((c) =>
    typeof c === 'string'
      ? new Paragraph({
          alignment: align,
          spacing: { after: 0, line: 252 },
          children: [r(nbNum(c), { bold, size: 20 })],
        })
      : c
  );
  return new TableCell({
    borders,
    width: { size: width, type: WidthType.DXA },
    shading: fill ? { fill, type: ShadingType.CLEAR } : undefined,
    margins: { top: 90, bottom: 90, left: 130, right: 130 },
    verticalAlign: vAlign || VerticalAlign.CENTER,
    children: paras,
  });
}

function table(widths, rows, { headerFill = BRAND_LIGHT } = {}) {
  const trs = rows.map(
    (row, i) =>
      new TableRow({
        tableHeader: i === 0,
        children: row.map((c, j) => {
          if (c && typeof c === 'object' && 'text' in c) {
            return cell(c.text, { width: widths[j], fill: i === 0 ? headerFill : c.fill, bold: i === 0 || c.bold, align: c.align });
          }
          return cell(c, { width: widths[j], fill: i === 0 ? headerFill : undefined, bold: i === 0 });
        }),
      })
  );
  return new Table({ width: { size: CW, type: WidthType.DXA }, columnWidths: widths, rows: trs });
}

